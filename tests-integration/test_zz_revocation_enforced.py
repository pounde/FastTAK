"""TAK Server itself refuses a revoked cert (DD-063).

Every other revocation test stops at "the serial is in ca.crl". These connect.

TAK Server has two checks, and which one covers a cert depends on who issued it:

- A cert enrolled through TAK Server (QR code, port 8446) is in TAK Server's
  own database. A revocation there is checked at every connection.
- A cert generated by the monitor exists only as files. The revocation list is
  the only check, and TAK Server reads the list when it starts.

The file name sorts last on purpose: the second test restarts tak-server, and
`test_stack_health.py` counts starts.
"""

import base64
import json
import socket
import ssl
import subprocess
import time
from pathlib import Path
from urllib.parse import parse_qs, urlparse

import httpx
import pytest
from cryptography import x509
from cryptography.hazmat.primitives import hashes, serialization
from cryptography.hazmat.primitives.asymmetric import rsa
from cryptography.x509.oid import NameOID

pytestmark = pytest.mark.integration

# Ports published by docker-compose.test.yml.
TAK_STREAM = ("localhost", 18089)
TAK_ENROLL_URL = "https://localhost:18446"

# TAK Server signs a request only when its subject is the user's name plus
# exactly the name entries init-config writes to CoreConfig.xml.
CSR_ORGANIZATION = "FastTAK"
CSR_UNIT = "TAK"

# How long a connection must stay open to count as accepted. TAK Server closes
# a client it refuses within a second of the handshake.
HOLD_SECONDS = 4


def _connect(cert: Path, key: Path) -> tuple[str, str]:
    """Connect to the streaming port with a client cert.

    Returns ("accepted" | "refused" | "unreachable", detail). "refused" means
    TAK Server answered and then turned the client away: a TLS alert, or a
    close right after the handshake. "unreachable" means nothing answered, as
    while TAK Server is starting.
    """
    context = ssl.SSLContext(ssl.PROTOCOL_TLS_CLIENT)
    context.check_hostname = False
    context.verify_mode = ssl.CERT_NONE
    context.load_cert_chain(str(cert), str(key))
    try:
        raw = socket.create_connection(TAK_STREAM, timeout=10)
    except OSError as exc:
        return "unreachable", repr(exc)
    try:
        with context.wrap_socket(raw) as tls:
            tls.settimeout(HOLD_SECONDS)
            try:
                data = tls.recv(1)
            except TimeoutError:
                return "accepted", f"still open after {HOLD_SECONDS}s"
            if data:
                return "accepted", "TAK Server sent data"
            return "refused", "closed by TAK Server after the handshake"
    except ssl.SSLError as exc:
        return "refused", repr(exc)
    except OSError as exc:
        # A reset during or after the handshake: something answered, then hung up.
        return "refused", repr(exc)


def _wait_for(cert: Path, key: Path, wanted: str, seconds: int) -> tuple[str, str]:
    """Connect until the outcome is `wanted`; return the last outcome either way."""
    deadline = time.monotonic() + seconds
    while True:
        outcome, detail = _connect(cert, key)
        if outcome == wanted or time.monotonic() > deadline:
            return outcome, detail
        time.sleep(5)


def _new_user(api, username: str, group: str) -> str:
    status, data = api(
        "POST",
        "/api/users",
        {"username": username, "name": "Revocation test", "groups": [group]},
    )
    assert status == 201, data
    return data["id"]


def _enroll(api, uid: str, username: str, directory: Path) -> tuple[Path, Path]:
    """Enroll a cert the way a device does, and return (cert, key) files."""
    status, data = api("POST", f"/api/users/{uid}/enroll")
    assert status == 200, data
    token = parse_qs(urlparse(data["enrollment_url"]).query)["token"][0]

    key = rsa.generate_private_key(public_exponent=65537, key_size=2048)
    csr = (
        x509.CertificateSigningRequestBuilder()
        .subject_name(
            x509.Name(
                [
                    x509.NameAttribute(NameOID.COMMON_NAME, username),
                    x509.NameAttribute(NameOID.ORGANIZATION_NAME, CSR_ORGANIZATION),
                    x509.NameAttribute(NameOID.ORGANIZATIONAL_UNIT_NAME, CSR_UNIT),
                ]
            )
        )
        .sign(key, hashes.SHA256())
    )
    response = httpx.post(
        f"{TAK_ENROLL_URL}/Marti/api/tls/signClient/v2?clientUid=revocation-test&version=2",
        content=csr.public_bytes(serialization.Encoding.PEM),
        headers={"Content-Type": "text/plain"},
        auth=(username, token),
        verify=False,
        timeout=30,
    )
    assert response.status_code == 200, f"{response.status_code} {response.text[:300]}"
    der = base64.b64decode(response.json()["signedCert"].replace("\n", "").replace(" ", ""))

    cert_file = directory / "enrolled.pem"
    key_file = directory / "enrolled.key"
    cert_file.write_bytes(
        x509.load_der_x509_certificate(der).public_bytes(serialization.Encoding.PEM)
    )
    key_file.write_bytes(
        key.private_bytes(
            serialization.Encoding.PEM,
            serialization.PrivateFormat.TraditionalOpenSSL,
            serialization.NoEncryption(),
        )
    )
    return cert_file, key_file


def test_an_enrolled_cert_is_refused_as_soon_as_it_is_revoked(api, run_id, user_group, tmp_path):
    username = f"tstenr_{run_id}"
    uid = _new_user(api, username, user_group)
    try:
        cert, key = _enroll(api, uid, username, tmp_path)

        outcome, detail = _wait_for(cert, key, "accepted", 30)
        assert outcome == "accepted", f"a valid enrolled cert should connect: {detail}"

        status, certs = api("GET", f"/api/users/{uid}/certs")
        assert status == 200, certs
        cert_ids = [c["cert_id"] for c in certs if c["cert_id"] is not None]
        assert len(cert_ids) == 1, f"expected the one enrolled cert in TAK Server's list: {certs}"

        status, data = api("POST", f"/api/users/{uid}/certs/revoke", {"cert_id": cert_ids[0]})
        assert status == 200, data

        outcome, detail = _wait_for(cert, key, "refused", 30)
        assert outcome == "refused", (
            "TAK Server still accepts an enrolled cert 30 seconds after it was revoked. "
            "DD-063 says its database check (x509checkRevocation) refuses such a cert "
            f"without a restart; that claim is wrong for this TAK Server version. {detail}"
        )
    finally:
        api("DELETE", f"/api/users/{uid}")


# The key the monitor writes is encrypted and may be unreadable from the host,
# so this connection is made inside the tak-server container. stdin stays open
# for a moment so an alert that arrives after the handshake (TLS 1.3) is read.
HANDSHAKE = (
    'sleep 3 | openssl s_client -connect 127.0.0.1:8089 -cert "$1.pem" -key "$1.key"'
    ' -pass pass:atakatak 2>&1; echo "exit=$?"'
)


def _handshake(compose_exec, cert_path: str) -> str:
    return compose_exec("tak-server", ["sh", "-c", HANDSHAKE, "sh", cert_path]).stdout


def _wait_until_tak_server_is_healthy(compose_cmd, compose_env, seconds: int = 420) -> None:
    deadline = time.monotonic() + seconds
    health = "unknown"
    while time.monotonic() < deadline:
        ps = subprocess.run(
            [*compose_cmd, "ps", "--format", "json", "tak-server"],
            capture_output=True, text=True, env=compose_env,
        )  # fmt: skip
        rows = [json.loads(line) for line in ps.stdout.splitlines() if line.strip()]
        health = rows[0].get("Health") if rows else "no container"
        if health == "healthy":
            return
        time.sleep(5)
    pytest.fail(f"tak-server was not healthy {seconds}s after the restart (last: {health})")


def test_a_monitor_generated_cert_is_refused_after_tak_server_restarts(
    api, compose_exec, compose_cmd, compose_env, run_id, user_group
):
    username = f"tstrev_{run_id}"
    uid = _new_user(api, username, user_group)
    cert_path = f"/opt/tak/certs/files/{username}-dev"
    try:
        status, data = api("POST", f"/api/users/{uid}/certs/generate", {"name": "dev"})
        assert status == 201, data

        output = _handshake(compose_exec, cert_path)
        assert "exit=0" in output and "alert" not in output, (
            f"a valid cert should connect before it is revoked:\n{output}"
        )

        status, data = api("POST", f"/api/users/{uid}/certs/revoke", {"cert_name": "dev"})
        assert status == 200, data

        # TAK Server reads ca.crl when it starts, and not again.
        subprocess.run([*compose_cmd, "restart", "tak-server"], check=True, env=compose_env)
        _wait_until_tak_server_is_healthy(compose_cmd, compose_env)

        # The streaming port can open a little after the health check passes,
        # so a failed connection is retried; only the alert counts as a refusal.
        deadline = time.monotonic() + 120
        while "certificate revoked" not in output and time.monotonic() < deadline:
            time.sleep(10)
            output = _handshake(compose_exec, cert_path)
        assert "certificate revoked" in output, (
            "TAK Server did not answer a revoked cert with 'certificate revoked' after a "
            f"restart, so it is not reading ca.crl:\n{output}"
        )
    finally:
        api("DELETE", f"/api/users/{uid}")
